#!/usr/bin/env python3
"""S8 appendix table for hyman2026local (Master Plan S8, ruling G15(a'); post hoc, descriptive).

Writes the rows of Table A1: for each of the 17 primary configurations, the budget beta, the
overhead x_C = H/K_G as Section 2 defines it (one cost per update C = K_G/U_G, median times), and
two counterfactuals computed from the same S4 timers:

  x_C without the time-step difference: x_C + (dt_G - dt_L)/K_G
  x_C without the time-step and stability-check differences: the above + (cfl_G - cfl_L)/K_G

where dt is the global time-step computation and cfl the per-level stability check, each the median
over repetitions. These are the quantities behind the sentence in Section 5.3 ("without its
difference between the schedules x_C would be positive in 6 of the 17 configurations, and without
the stability check as well in 3"), computed exactly as validation/s6_tables.py computes them
(section D, "sensitivity"). Nothing here enters the R1.2 verdict.

Usage:  python3 validation/s8_appendix_table.py validation/data --evaluation validation/evaluation_s5.json \
            --out validation/tableA1_rows.tex
Python 3; imports validation/fit.py (NumPy, SciPy) and validation/s6_tables.py. Deterministic.
"""
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fit as F                      # noqa: E402  (same loader s6_tables.py uses)
import s6_tables as S6               # noqa: E402  (median timer decomposition, ORDER, LABEL)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data")
    ap.add_argument("--evaluation", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    sec = json.load(open(a.evaluation))["secondary"]
    med = S6.load(a.data)
    full = F.load(a.data, allow_heldout_timing=True)

    def U(c, s):
        return sum(x["A"] * x["N"] for x in F.lv_list(full[c], s))

    xc, nodt, nocfl = {}, {}, {}
    for c in sec:
        t = full[c]["timing"]
        KG = t["global"]["K"]
        C = KG / U(c, "global")
        xc[c] = (t["subcycle"]["T"] - t["global"]["T"] + C * (U(c, "global") - U(c, "subcycle"))) / KG
        nodt[c] = xc[c] + (med[(c, "global")]["dt"] - med[(c, "subcycle")]["dt"]) / KG
        nocfl[c] = nodt[c] + (med[(c, "global")]["cfl"] - med[(c, "subcycle")]["cfl"]) / KG

    rows = []
    for d, feat in S6.ORDER:
        for c in sorted((c for c, v in sec.items() if str(v["dim"]) == d and v["feature"] == feat),
                        key=lambda c: sec[c]["L"]):
            v = sec[c]
            rows.append((d, f"{d} & {S6.LABEL[feat]} & {v['delta']} & {v['L']} & {v['beta']:.3f} & "
                            f"${xc[c]:.3f}$ & ${nodt[c]:.3f}$ & ${nocfl[c]:.3f}$\\\\"))
    with open(a.out, "w") as f:
        f.write("% generated by validation/s8_appendix_table.py; do not edit by hand\n")
        prev = None
        for d, line in rows:
            if prev is not None and d != prev:
                f.write("\\addlinespace\n")
            f.write(line + "\n")
            prev = d

    n = len(sec)
    print(f"A1 Table A1: {len(rows)} rows written to {a.out}")
    print(f"   x_C {min(xc.values()):+.3f} to {max(xc.values()):+.3f}; negative in {sum(x < 0 for x in xc.values())} of {n}")
    print(f"   without the dt difference: {min(nodt.values()):+.3f} to {max(nodt.values()):+.3f}; "
          f"positive in {sum(x > 0 for x in nodt.values())} of {n}: "
          + ", ".join(c for c in sorted(nodt) if nodt[c] > 0))
    print(f"   without the dt and cfl differences: {min(nocfl.values()):+.3f} to {max(nocfl.values()):+.3f}; "
          f"positive in {sum(x > 0 for x in nocfl.values())} of {n}: "
          + ", ".join(c for c in sorted(nocfl) if nocfl[c] > 0))
    print(f"   counterfactual still below beta (subcycling would still win): without dt {sum(nodt[c] < sec[c]['beta'] for c in sec)} of {n}; "
          f"without dt and cfl {sum(nocfl[c] < sec[c]['beta'] for c in sec)} of {n}")
    print(f"   smallest margin beta - x without dt: {min(sec[c]['beta'] - nodt[c] for c in sec):.3f} "
          f"({min(sec, key=lambda c: sec[c]['beta'] - nodt[c])}); without dt and cfl: "
          f"{min(sec[c]['beta'] - nocfl[c] for c in sec):.3f} ({min(sec, key=lambda c: sec[c]['beta'] - nocfl[c])})")


if __name__ == "__main__":
    main()
